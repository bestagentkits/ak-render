#!/usr/bin/env node
/**
 * Generate `src/recipes/recipes.generated.ts` from `src/recipes/page-recipes/*.yaml`.
 *
 * A page recipe is a complete starter Page Spec. Its file opens with two
 * metadata comment lines, which the generator strips from the spec text:
 *
 *   # summary: <one line on what the page shows>
 *   # use-cases: <use case>; <use case>; ...
 *
 * The module embeds every spec as a string so the compiled package never reads
 * package files at runtime. The block list is collected from the parsed spec;
 * a unit test checks it against the compiler's own node types.
 *
 * Usage: node scripts/generate-recipes-module.mjs [--check]
 */

import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const recipesDir = join(root, 'src/recipes/page-recipes');
const target = join(root, 'src/recipes/recipes.generated.ts');
const require = createRequire(import.meta.url);

const NAME = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/u;
const SUMMARY_LINE = /^# summary: (.+)\n/u;
const USE_CASES_LINE = /^# use-cases: (.+)\n/u;
const MAX_SUMMARY = 120;
const MAX_USE_CASES = 4;
const MAX_USE_CASE_LENGTH = 48;

/** Props whose value is a list of child blocks (the slot props of layout blocks). */
const BLOCK_LIST_KEYS = new Set(['blocks', 'sidebar', 'aside', 'rail']);

function fail(file, message) {
  throw new Error(`${file}: ${message}`);
}

/** Every block type in a block list, including blocks nested in slots and items. */
function collectTypes(list, types) {
  if (!Array.isArray(list)) return;
  for (const block of list) {
    if (block === null || typeof block !== 'object') continue;
    if (typeof block.type === 'string') types.add(block.type);
    for (const [key, value] of Object.entries(block)) {
      if (!Array.isArray(value)) continue;
      if (BLOCK_LIST_KEYS.has(key)) {
        collectTypes(value, types);
        continue;
      }
      // Compound items (tabs, accordion, carousel, bento) nest blocks per item.
      for (const item of value) {
        if (item !== null && typeof item === 'object') collectTypes(item.blocks, types);
      }
    }
  }
}

function readRecipe(file) {
  const name = file.replace(/\.yaml$/u, '');
  if (!NAME.test(name)) fail(file, 'the file name must be kebab-case');
  let text = readFileSync(join(recipesDir, file), 'utf8').replace(/\r\n/gu, '\n');

  const summary = SUMMARY_LINE.exec(text)?.[1]?.trim();
  if (summary === undefined) fail(file, 'the first line must be "# summary: ..."');
  if (summary.length > MAX_SUMMARY) fail(file, `summary is over ${MAX_SUMMARY} characters`);
  text = text.replace(SUMMARY_LINE, '');

  const useCasesLine = USE_CASES_LINE.exec(text)?.[1];
  if (useCasesLine === undefined) fail(file, 'the second line must be "# use-cases: a; b"');
  const useCases = useCasesLine.split(';').map((entry) => entry.trim());
  if (useCases.length === 0 || useCases.length > MAX_USE_CASES || useCases.includes('')) {
    fail(file, `use-cases must list 1 to ${MAX_USE_CASES} entries separated by ";"`);
  }
  for (const useCase of useCases) {
    if (useCase.length > MAX_USE_CASE_LENGTH) {
      fail(file, `use case "${useCase}" is over ${MAX_USE_CASE_LENGTH} characters`);
    }
  }
  const spec = text.replace(USE_CASES_LINE, '').replace(/^(?:[ \t]*\n)+/u, '');

  const document = parse(spec);
  if (document === null || typeof document !== 'object' || !Array.isArray(document.blocks)) {
    fail(file, 'the spec must be a mapping with a "blocks" list');
  }
  const types = new Set();
  collectTypes(document.blocks, types);
  const blocks = [...types].sort();
  return { name, summary, useCases, blocks, spec };
}

/** A template literal holding `value` verbatim. */
function templateLiteral(value) {
  return `\`${value.replace(/\\/gu, '\\\\').replace(/`/gu, '\\`').replace(/\$\{/gu, '\\${')}\``;
}

const recipes = readdirSync(recipesDir)
  .filter((file) => file.endsWith('.yaml'))
  .sort()
  .map(readRecipe);
if (recipes.length === 0) throw new Error(`no recipes found in ${recipesDir}`);

const entries = recipes
  .map(
    (recipe) => `  {
    name: ${JSON.stringify(recipe.name)},
    summary: ${JSON.stringify(recipe.summary)},
    useCases: ${JSON.stringify(recipe.useCases)},
    blocks: ${JSON.stringify(recipe.blocks)},
    spec: ${templateLiteral(recipe.spec)},
  },`,
  )
  .join('\n');

const source = `/**
 * Generated by scripts/generate-recipes-module.mjs from src/recipes/page-recipes. Do not edit.
 * Change a recipe's YAML file, then run pnpm recipes:generate.
 */

import type { PageRecipe } from './index.js';

/** Every page recipe, sorted by name. */
export const PAGE_RECIPES: readonly PageRecipe[] = [
${entries}
];
`;

// Format with the repository's own formatter so the committed module passes lint.
const output = execFileSync(
  process.execPath,
  [require.resolve('@biomejs/biome/bin/biome'), 'format', `--stdin-file-path=${target}`],
  { cwd: root, input: source, encoding: 'utf8' },
);

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // A missing module is reported as stale below.
  }
  if (current !== output) {
    console.error('page recipes are stale: run pnpm recipes:generate');
    process.exit(1);
  }
  console.log('page recipes are up to date');
} else {
  writeFileSync(target, output, 'utf8');
  console.log(`wrote ${target} (${output.length} bytes, ${recipes.length} recipes)`);
}
