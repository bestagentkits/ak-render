#!/usr/bin/env node
/**
 * Generate `src/render/embedded-fonts.generated.ts` from `assets/fonts`.
 *
 * Each family directory holds two WOFF2 subsets of an SIL OFL 1.1 variable font
 * (taken unmodified from its Fontsource package) and the font's `OFL.txt`. The
 * generated module carries them as base64 so the compiled package can inline a
 * theme's display face without reading files or touching the network.
 *
 * Usage: node scripts/generate-embedded-fonts.mjs [--check]
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fontsDir = join(root, 'assets/fonts');
const target = join(root, 'src/render/embedded-fonts.generated.ts');

/** Unicode ranges of the Fontsource subsets, copied from each package's CSS. */
const LATIN =
  'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const VIETNAMESE =
  'U+0102-0103,U+0110-0111,U+0128-0129,U+0168-0169,U+01A0-01A1,U+01AF-01B0,U+0300-0301,U+0303-0304,U+0308-0309,U+0323,U+0329,U+1EA0-1EF9,U+20AB';

/** Families in a fixed order; `family` is the namespaced name theme stacks use. */
const FAMILIES = [
  { dir: 'geist', family: 'AK Geist', name: 'Geist', weight: '100 900' },
  { dir: 'fraunces', family: 'AK Fraunces', name: 'Fraunces', weight: '100 900' },
  {
    dir: 'bricolage-grotesque',
    family: 'AK Bricolage Grotesque',
    name: 'Bricolage Grotesque',
    weight: '200 800',
  },
  { dir: 'jetbrains-mono', family: 'AK JetBrains Mono', name: 'JetBrains Mono', weight: '100 800' },
  { dir: 'inter-tight', family: 'AK Inter Tight', name: 'Inter Tight', weight: '100 900' },
  {
    dir: 'plus-jakarta-sans',
    family: 'AK Plus Jakarta Sans',
    name: 'Plus Jakarta Sans',
    weight: '200 800',
  },
];

/** The first copyright statement of the licence, which the CSS notice repeats. */
function copyright(dir) {
  const first = readFileSync(join(fontsDir, dir, 'OFL.txt'), 'utf8').split('\n')[0] ?? '';
  const statement = first.split(/ [A-Za-z-]+(?:\[[^\]]*\])?\.ttf:/u)[0]?.trim() ?? '';
  if (!statement.startsWith('Copyright')) throw new Error(`${dir}/OFL.txt has no copyright line`);
  return statement;
}

function base64(dir, subset) {
  return readFileSync(join(fontsDir, dir, `${subset}.woff2`)).toString('base64');
}

const entries = FAMILIES.map(
  ({ dir, family, name, weight }) => `  {
    family: ${JSON.stringify(family)},
    name: ${JSON.stringify(name)},
    weight: ${JSON.stringify(weight)},
    copyright: ${JSON.stringify(copyright(dir))},
    latin: '${base64(dir, 'latin')}',
    vietnamese: '${base64(dir, 'vietnamese')}',
  },`,
).join('\n');

const output = `/**
 * Generated by scripts/generate-embedded-fonts.mjs from assets/fonts. Do not edit.
 *
 * Variable WOFF2 subsets of SIL Open Font License 1.1 fonts, unmodified from
 * their Fontsource packages. The licence texts ship in assets/fonts/<family>/OFL.txt.
 */

export interface EmbeddedFont {
  /** Namespaced family name a theme font stack refers to. */
  family: string;
  /** Upstream family name, for the licence notice. */
  name: string;
  /** Variable weight range. */
  weight: string;
  copyright: string;
  /** Base64 WOFF2 data per subset. */
  latin: string;
  vietnamese: string;
}

export const LATIN_RANGE = '${LATIN}';
export const VIETNAMESE_RANGE = '${VIETNAMESE}';

export const EMBEDDED_FONTS: readonly EmbeddedFont[] = [
${entries}
];
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // A missing module is reported as stale below.
  }
  if (current !== output) {
    console.error('embedded fonts are stale: run pnpm fonts:generate');
    process.exit(1);
  }
  console.log('embedded fonts are up to date');
} else {
  writeFileSync(target, output, 'utf8');
  console.log(`wrote ${target} (${output.length} bytes, ${FAMILIES.length} families)`);
}
