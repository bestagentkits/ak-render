#!/usr/bin/env node
/**
 * Generate `src/blocks/three/three-runtime.generated.ts`: the shared 3D runtime
 * (`src/blocks/three/runtime/entry.js`) bundled with the pinned Three.js into
 * one self-contained, minified script string.
 *
 * The compiler inlines that string into pages that use a 3D block, so the page
 * stays offline and the compiler stays browser- and network-free. The bundle is
 * built with a pinned esbuild and fixed options, so it is byte-stable.
 *
 * Usage: node scripts/generate-three-runtime.mjs [--check]
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'src/blocks/three/runtime/entry.js');
const target = join(root, 'src/blocks/three/three-runtime.generated.ts');
const threeVersion = JSON.parse(
  readFileSync(join(root, 'node_modules/three/package.json'), 'utf8'),
).version;

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  minify: true,
  format: 'iife',
  globalName: '__akThree',
  target: 'es2022',
  legalComments: 'none',
  charset: 'utf8',
  logLevel: 'silent',
});
// The bundle keeps one license line, so every emitted page carries the notice MIT asks for.
const code = `/*! three.js r${threeVersion.split('.')[1]} | MIT License | (c) 2010-2024 three.js authors */
${result.outputFiles[0].text.trim()}`;
if (/\beval\(|new Function\(/u.test(code)) throw new Error('3D runtime must not evaluate code');

const output = `// Generated by scripts/generate-three-runtime.mjs. Do not edit.
// three@${threeVersion} (MIT, see THIRD_PARTY_NOTICES.md) + src/blocks/three/runtime/entry.js

/** Pinned Three.js version inside the runtime. */
export const THREE_VERSION = ${JSON.stringify(threeVersion)};

/** The bundled 3D runtime; defines \`__akThree.boot\`. */
export const THREE_RUNTIME = ${JSON.stringify(code)};
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== output) {
    console.error('three-runtime.generated.ts is stale; run pnpm three:generate');
    process.exit(1);
  }
  console.log('three runtime up to date');
} else {
  writeFileSync(target, output);
  console.log(`wrote ${target} (${code.length} bytes, three@${threeVersion})`);
}
