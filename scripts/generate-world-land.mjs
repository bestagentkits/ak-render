#!/usr/bin/env node
/**
 * Builds `src/blocks/three/world-land.generated.ts`, the land outline the
 * `globe-3d` widget draws, from Natural Earth's 1:110m land polygons
 * (public domain, https://www.naturalearthdata.com/about/terms-of-use/).
 *
 *   node scripts/generate-world-land.mjs path/to/ne_110m_land.geojson
 *
 * Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_land.geojson
 *
 * Rings are simplified (Douglas-Peucker, 0.2 degrees), quantized to tenths of
 * a degree and delta-encoded into one string, so the module is compact and
 * the output is byte-identical for the same input.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const input = process.argv[2];
if (!input) {
  console.error('usage: node scripts/generate-world-land.mjs <ne_110m_land.geojson>');
  process.exit(1);
}
const TOLERANCE = 0.2;
const MIN_POINTS = 4;

function simplify(points, tolerance) {
  if (points.length <= 3) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = 1;
  keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length > 0) {
    const [a, b] = stack.pop();
    const [ax, ay] = points[a];
    const [bx, by] = points[b];
    const length = Math.hypot(bx - ax, by - ay);
    let worst = -1;
    let at = -1;
    for (let i = a + 1; i < b; i += 1) {
      const [px, py] = points[i];
      // A closed ring starts and ends on one point: measure from it directly.
      const distance =
        length === 0
          ? Math.hypot(px - ax, py - ay)
          : Math.abs((bx - ax) * (ay - py) - (ax - px) * (by - ay)) / length;
      if (distance > worst) {
        worst = distance;
        at = i;
      }
    }
    if (worst > tolerance && at > 0) {
      keep[at] = 1;
      stack.push([a, at], [at, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const geojson = JSON.parse(readFileSync(input, 'utf8'));
const rings = [];
for (const feature of geojson.features) {
  const geometry = feature.geometry;
  const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  for (const polygon of polygons)
    for (const ring of polygon) {
      const simple = simplify(ring, TOLERANCE).map(([lon, lat]) => [
        Math.round(lon * 10),
        Math.round(lat * 10),
      ]);
      // Drop the closing point (rings close implicitly) and repeated points.
      const points = simple.filter(
        (p, i) => i === 0 || p[0] !== simple[i - 1][0] || p[1] !== simple[i - 1][1],
      );
      const last = points[points.length - 1];
      if (last && last[0] === points[0][0] && last[1] === points[0][1]) points.pop();
      if (points.length >= MIN_POINTS) rings.push(points);
    }
}
const encoded = rings
  .map((points) =>
    points
      .flatMap(([x, y], i) => (i === 0 ? [x, y] : [x - points[i - 1][0], y - points[i - 1][1]]))
      .join(','),
  )
  .join(';');

const out = `/**
 * Generated by scripts/generate-world-land.mjs from Natural Earth 1:110m land
 * (public domain, naturalearthdata.com). Do not edit.
 *
 * Rings are separated by \`;\`. Each ring is a comma-separated list of
 * longitude/latitude pairs in tenths of a degree: the first pair absolute,
 * every later pair a delta from the one before. Rings close implicitly.
 */

export const WORLD_LAND =
  '${encoded}';
`;
const target = join(
  dirname(fileURLToPath(import.meta.url)),
  '../src/blocks/three/world-land.generated.ts',
);
writeFileSync(target, out);
console.log(`world land: ${rings.length} rings, ${encoded.length} chars`);
