#!/usr/bin/env node
/**
 * Generate cross-preset snapshots.
 *
 * One content spec is rendered under every built-in preset and committed, so a
 * theme change that alters emitted bytes is visible in review instead of being
 * caught only by a hash assertion. `--check` fails when the committed snapshots
 * are stale, which is what CI runs.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const checkMode = process.argv.includes('--check');

let compile;
let themePresetNames;
try {
  // One import of the built entry point keeps the generated output and the
  // snapshot writer on exactly the same compiler build.
  ({ compile, themePresetNames } = await import(new URL('../dist/index.js', import.meta.url)));
} catch {
  console.error('generate-theme-snapshots: dist/ is missing; run "pnpm build" first');
  process.exit(1);
}

const specPath = fileURLToPath(new URL('../fixtures/pages/theme-showcase.yaml', import.meta.url));
const snapshotDir = fileURLToPath(new URL('../fixtures/snapshots', import.meta.url));
const spec = readFileSync(specPath, 'utf8');

mkdirSync(snapshotDir, { recursive: true });

const stale = [];
const written = [];

for (const preset of themePresetNames()) {
  const result = compile(spec, { theme: preset, source: 'theme-showcase.yaml' });
  const target = `${snapshotDir}/theme-${preset}.html`;
  const expected = `${header(preset, result.hash)}${result.html}`;

  if (checkMode) {
    if (!existsSync(target)) {
      stale.push(`${relative(repoRoot, target)} is missing`);
      continue;
    }
    if (readFileSync(target, 'utf8') !== expected) {
      stale.push(`${relative(repoRoot, target)} is stale`);
    }
    continue;
  }

  writeFileSync(target, expected, 'utf8');
  written.push(`${preset} (${result.bytes} bytes, hash ${result.hash})`);
}

if (checkMode) {
  if (stale.length > 0) {
    console.error('generate-theme-snapshots: snapshots need regeneration');
    for (const problem of stale) console.error(`  - ${problem}`);
    console.error('  run "pnpm snapshots:generate"');
    process.exit(1);
  }
  console.log(`generate-theme-snapshots: ${themePresetNames().length} snapshots are up to date`);
  process.exit(0);
}

console.log(`generate-theme-snapshots: wrote ${written.length} snapshots`);
for (const line of written) console.log(`  - ${line}`);

/** A short banner so a snapshot's provenance and hash are visible in review. */
function header(preset, hash) {
  return `<!-- generated by scripts/generate-theme-snapshots.mjs: preset=${preset} hash=${hash} -->\n`;
}
